import { documentLink } from '@/lib/document-link';
import type { StudentProjectDocument } from '../types';

export const MAX_STUDENT_DOCUMENT_BYTES = 4 * 1024 * 1024; // 4 MB (mismo límite que el wizard de inscripción)
export const MAX_SECONDARY_FILES_PER_UPLOAD = 5;

export const POSTER_ACCEPT = '.pdf,.jpg,.jpeg,.png';
export const SECONDARY_DOCUMENT_ACCEPT =
  '.pdf,.doc,.docx,.ppt,.pptx,.jpg,.jpeg,.png';

const POSTER_EXTENSIONS = new Set(['pdf', 'jpg', 'jpeg', 'png']);
const SECONDARY_EXTENSIONS = new Set([
  'pdf',
  'doc',
  'docx',
  'ppt',
  'pptx',
  'jpg',
  'jpeg',
  'png',
]);

const getFileExtension = (fileName: string): string => {
  const parts = fileName.trim().toLowerCase().split('.');
  return parts.length > 1 ? parts[parts.length - 1] : '';
};

const readBlobHeaderBytes = async (
  blob: Blob,
  length: number,
): Promise<Uint8Array> => {
  const slice = blob.slice(0, length);

  if (typeof slice.arrayBuffer === 'function') {
    return new Uint8Array(await slice.arrayBuffer());
  }

  if (typeof FileReader !== 'undefined') {
    return new Promise<Uint8Array>((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => {
        if (reader.result instanceof ArrayBuffer) {
          resolve(new Uint8Array(reader.result));
        } else {
          reject(new Error('Unexpected FileReader result'));
        }
      };
      reader.onerror = () =>
        reject(reader.error ?? new Error('FileReader error'));
      reader.readAsArrayBuffer(slice);
    });
  }

  return new Uint8Array(await new Response(slice).arrayBuffer());
};

const matchesSignature = (bytes: Uint8Array, signature: number[]): boolean =>
  bytes.length >= signature.length &&
  signature.every((expected, idx) => bytes[idx] === expected);

const hasValidMagicBytesForExtension = async (
  file: File,
  ext: string,
): Promise<boolean> => {
  if (file.size < 4) return false;

  const bytes = await readBlobHeaderBytes(file, 8);

  switch (ext) {
    case 'pdf':
      // %PDF-
      return matchesSignature(bytes, [0x25, 0x50, 0x44, 0x46, 0x2d]);
    case 'png':
      // \x89PNG
      return matchesSignature(bytes, [0x89, 0x50, 0x4e, 0x47]);
    case 'jpg':
    case 'jpeg':
      // JPEG SOI
      return matchesSignature(bytes, [0xff, 0xd8, 0xff]);
    case 'docx':
    case 'pptx':
      // OOXML ZIP header PK\x03\x04
      return matchesSignature(bytes, [0x50, 0x4b, 0x03, 0x04]);
    case 'doc':
    case 'ppt':
      // OLE Compound File header
      return matchesSignature(bytes, [0xd0, 0xcf, 0x11, 0xe0]);
    default:
      return false;
  }
};

export const validatePosterFile = async (
  file: File | null | undefined,
): Promise<string | null> => {
  if (!file) {
    return 'Debes seleccionar un archivo para el póster.';
  }

  if (file.size <= 0) {
    return 'El archivo seleccionado está vacío.';
  }

  if (file.size > MAX_STUDENT_DOCUMENT_BYTES) {
    return 'El póster supera el tamaño máximo permitido de 4 MB.';
  }

  const ext = getFileExtension(file.name);
  if (!POSTER_EXTENSIONS.has(ext)) {
    return 'Formato no permitido para el póster. Solo se aceptan archivos PDF, JPG o PNG.';
  }

  try {
    const validSignature = await hasValidMagicBytesForExtension(file, ext);
    if (!validSignature) {
      return 'El contenido del archivo no corresponde a un PDF o imagen (JPG/PNG) válido.';
    }
  } catch {
    return 'No pudimos leer el archivo seleccionado. Intenta nuevamente.';
  }

  return null;
};

export const validateSupportingFiles = async (
  files: File[],
): Promise<string | null> => {
  if (!Array.isArray(files) || files.length === 0) {
    return 'Debes seleccionar al menos un documento.';
  }

  if (files.length > MAX_SECONDARY_FILES_PER_UPLOAD) {
    return `Puedes subir hasta ${MAX_SECONDARY_FILES_PER_UPLOAD} documentos a la vez.`;
  }

  for (const file of files) {
    if (file.size <= 0) {
      return `El archivo "${file.name}" está vacío.`;
    }

    if (file.size > MAX_STUDENT_DOCUMENT_BYTES) {
      return `El archivo "${file.name}" supera el límite de 4 MB.`;
    }

    const ext = getFileExtension(file.name);
    if (!SECONDARY_EXTENSIONS.has(ext)) {
      return `El archivo "${file.name}" tiene un formato no permitido.`;
    }

    try {
      const validSignature = await hasValidMagicBytesForExtension(file, ext);
      if (!validSignature) {
        return `El contenido de "${file.name}" no coincide con su extensión .${ext}.`;
      }
    } catch {
      return `No pudimos verificar la integridad de "${file.name}". Intenta nuevamente.`;
    }
  }

  return null;
};

/**
 * Distinguishes real backend document ids from synthetic fallback ids (`document-0`)
 * generated by `adaptDocument` when a payload omits `id`.
 */
export const hasRealDocumentId = (
  id: string | number | null | undefined,
): boolean => {
  if (id === null || id === undefined) return false;
  const trimmed = String(id).trim();
  if (!trimmed) return false;
  return !/^document-\d+$/i.test(trimmed);
};

const isSafeHref = (url: string | null | undefined): boolean => {
  if (!url) return false;
  const trimmed = url.trim();
  if (trimmed.startsWith('/')) return true;
  try {
    const parsed = new URL(trimmed);
    return parsed.protocol === 'http:' || parsed.protocol === 'https:';
  } catch {
    return false;
  }
};

/**
 * Uses the gateway's stable redirect endpoint (`/api/projects/:projectId/documents/:id/open`)
 * whenever both ids are real numeric backend ids so SAS URLs never expire mid-session;
 * falls back to a validated `doc.url` for mock/fixture records.
 */
export const resolveStudentDocumentHref = (
  doc: Pick<StudentProjectDocument, 'id' | 'url'>,
  projectId: string | number | null | undefined,
): string => {
  const cleanDocId = String(doc.id ?? '').trim();
  const cleanProjectId = String(projectId ?? '').trim();

  if (
    hasRealDocumentId(cleanDocId) &&
    /^\d+$/.test(cleanDocId) &&
    /^\d+$/.test(cleanProjectId)
  ) {
    return documentLink({ id: cleanDocId, projectId: cleanProjectId });
  }

  return isSafeHref(doc.url) ? doc.url.trim() : '#';
};

