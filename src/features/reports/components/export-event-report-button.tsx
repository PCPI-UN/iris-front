"use client";

import { Button } from "@heroui/button";
import { useEffect, useRef, useState } from "react";

import {
  Dropdown,
  DropdownItem,
  DropdownMenu,
  DropdownTrigger,
} from "@/components/ui/dropdown";
import { useCategoriesByEvent } from "@/features/projects/api/use-category";

import {
  downloadEvaluationReport,
  EvaluationReportCategory,
  getEvaluationReportErrorMessage,
} from "../api/download-evaluation-report";

type ExportState = "idle" | "loading" | "success" | "error";

const ALL_CATEGORIES_KEY = "all";

interface ExportEventReportButtonProps {
  eventId: number;
  label?: string;
  onError?: (err: Error) => void;
}

const toCategories = (raw: unknown): EvaluationReportCategory[] =>
  (Array.isArray(raw) ? raw : [])
    .map((category) => ({
      id: Number(category?.id),
      // Categories are named by their `code` (as in the categories list)
      name: String(
        category?.code ?? category?.name ?? category?.description ?? "",
      ).trim(),
    }))
    .filter((category) => Number.isInteger(category.id) && category.id > 0);

/**
 * Downloads the evaluation report generated by the backend: one Excel per
 * category of the event (the report is always of one category).
 */
export function ExportEventReportButton({
  eventId,
  label = "Exportar reporte",
  onError,
}: ExportEventReportButtonProps) {
  const [state, setState] = useState<ExportState>("idle");
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const resetTimer = useRef<ReturnType<typeof setTimeout>>();

  const categoriesQuery = useCategoriesByEvent(eventId || undefined);
  const categories = toCategories(categoriesQuery.data?.categories);

  useEffect(() => () => clearTimeout(resetTimer.current), []);

  const resetLater = (ms: number) => {
    clearTimeout(resetTimer.current);
    resetTimer.current = setTimeout(() => {
      setState("idle");
      setErrorMessage(null);
    }, ms);
  };

  async function handleExport(selected: EvaluationReportCategory[]) {
    if (selected.length === 0) return;

    setState("loading");
    setErrorMessage(null);

    try {
      // One request and one file per category, one after the other so the
      // browser does not block several simultaneous downloads
      for (const category of selected) {
        await downloadEvaluationReport({ eventId, categoryId: category.id });
      }
      setState("success");
      resetLater(3000);
    } catch (err) {
      const error = err instanceof Error ? err : new Error(String(err));
      setErrorMessage(getEvaluationReportErrorMessage(err));
      setState("error");
      onError?.(error);
      resetLater(5000);
    }
  }

  const hasNoCategories =
    !!eventId && categoriesQuery.isSuccess && categories.length === 0;
  const isDisabled =
    !eventId ||
    categoriesQuery.isLoading ||
    hasNoCategories ||
    state === "loading" ||
    state === "success";

  const button = (
    <Button
      type="button"
      onPress={
        categories.length > 1 ? undefined : () => void handleExport(categories)
      }
      isDisabled={isDisabled}
      aria-live="polite"
      aria-busy={state === "loading"}
      variant={state === "idle" ? "faded" : "flat"}
      className={[
        "transition-all duration-500",
        state === "idle" &&
          "border text-white bg-gradient-to-r from-cyan-500/10 to-cyan-500/5 hover:bg-white/10 active:bg-cyan-500",
        state === "loading" &&
          "cursor-not-allowed bg-gradient-to-r from-cyan-500/10 to-cyan-500/5 text-white",
        state === "success" && "bg-cyan-400 cursor-default text-white",
        state === "error" && "bg-red-600 text-white hover:bg-red-700",
      ]
        .filter(Boolean)
        .join(" ")}
    >
      {state === "loading" && <SpinnerIcon />}
      {state === "success" && <CheckIcon />}
      {state === "error" && <AlertIcon />}
      {state === "idle" && <DownloadIcon />}

      {state === "idle" && label}
      {state === "loading" && "Descargando…"}
      {state === "success" && "¡Descargado!"}
      {state === "error" && "Reintentar"}
    </Button>
  );

  return (
    <div className="inline-flex flex-col items-start gap-1.5">
      {categories.length > 1 && !isDisabled ? (
        <Dropdown>
          <DropdownTrigger>{button}</DropdownTrigger>
          <DropdownMenu
            aria-label="Categoría del reporte"
            onAction={(key) => {
              const selected =
                key === ALL_CATEGORIES_KEY
                  ? categories
                  : categories.filter((c) => String(c.id) === String(key));
              void handleExport(selected);
            }}
            items={[
              ...categories.map((c) => ({
                key: String(c.id),
                label: c.name || `Categoría ${c.id}`,
              })),
              { key: ALL_CATEGORIES_KEY, label: "Todas las categorías" },
            ]}
          >
            {(item) => (
              <DropdownItem
                key={item.key}
                showDivider={
                  item.key === String(categories[categories.length - 1].id)
                }
              >
                {item.label}
              </DropdownItem>
            )}
          </DropdownMenu>
        </Dropdown>
      ) : (
        button
      )}

      {hasNoCategories && (
        <p className="max-w-xs text-xs text-default-500">
          El evento no tiene categorías para generar el reporte.
        </p>
      )}

      {state === "error" && errorMessage && (
        <p className="max-w-xs text-xs text-red-600" role="alert">
          {errorMessage}
        </p>
      )}
    </div>
  );
}

